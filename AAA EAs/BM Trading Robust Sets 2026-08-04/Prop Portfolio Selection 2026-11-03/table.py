"""Apply the frozen PLAN.md choice rule to CH-*.json (development only), then write RESULTS.md / CHOICE.json (and funded tables if FU-*.json exist).
python table.py"""
import json, statistics
from pathlib import Path

R = Path(__file__).resolve().parent
LABEL = {'FTMO17': 'FTMO guarded 17', 'CUR17': 'Current 14 + ORB 17, no guard', 'PR9': 'Prop ready 9 (DI ON)', 'BP9': 'Best Prop 9 (DI OFF)',
         'BP15': 'Best Prop 15 (DI OFF)', 'C7': 'Custom 7, guarded', 'C7U': 'Custom 7, no guard', 'FV9': 'funded_v1 roster, guarded',
         'T5': 'Turbo 5 roster, guarded', 'FULL': 'Full EA core 27, no guard'}
CH = {(p.stem.split('-')[1], p.stem.split('-')[2]): json.loads(p.read_text(encoding='utf-8')) for p in sorted(R.glob('CH-*.json'))}
pct = lambda v: '–' if v is None else f'{100 * v:.0f}%'  # noqa: E731
num = lambda v: '–' if v is None else f'{v:g}'  # noqa: E731

dev = {k: v['hist']['dev'] for k, v in CH.items()}
eligible = [k for k, d in dev.items() if d['breach'] <= 0.05]
rank = sorted(eligible, key=lambda k: (-dev[k]['pass_both_180'], dev[k]['median_days_funded'] if dev[k]['median_days_funded'] is not None else 9e9))
val_median = statistics.median(v['hist']['val']['pass_both_180'] for v in CH.values()) if CH else None
pick = next((k for k in rank if CH[k]['hist']['val']['pass_both_180'] >= val_median), None)
choice = dict(rank=[f'{a} {b}%' for a, b in rank], dev_rank_1=f'{rank[0][0]} {rank[0][1]}%' if rank else None, validation_median=val_median,
              pick=f'{pick[0]} {pick[1]}%' if pick else None, pick_is_dev_rank_1=bool(rank) and pick == rank[0],
              funded_stage=[f'{a} {b}' for a, b in ([pick] if pick else []) + [k for k in rank if k != pick][:2]])
md = ['# Prop portfolio selection: FTMO 2-step $100k, Nasdaq 5M ATR6 everywhere (generated by table.py)', '',
      'Frozen engine of Portfolio Prop Comparison 2026-10-22; rules, candidates and choice rule in PLAN.md (frozen before results). '
      'Pass = both phases within 180 days of purchase. History = every weekday start, grouped by start date. MC = 2,000 block-bootstrap paths.', '',
      f"**Development rank 1:** {choice['dev_rank_1']} · **validation median:** {pct(val_median)} · **PICK:** **{choice['pick']}**"
      + ('' if choice['pick_is_dev_rank_1'] else ' (development rank 1 failed the validation check)'), '',
      '| Candidate | Risk | Dev pass (breach) | Dev median days to funded | Val pass (breach) | OOS pass (breach) | All pass | MC pass | MC breach | MC median days to funded | MC stuck at buffer | Median challenge trades |',
      '|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
for k in sorted(CH, key=lambda k: -dev[k]['pass_both_180']):
    h = CH[k]['hist']; m = CH[k]['mc']; star = ' **←**' if k == pick else ''
    md.append(f"| {LABEL[k[0]]}{star} | {k[1]}% | {pct(h['dev']['pass_both_180'])} ({pct(h['dev']['breach'])}) | {num(h['dev']['median_days_funded'])} | "
              f"{pct(h['val']['pass_both_180'])} ({pct(h['val']['breach'])}) | {pct(h['oos']['pass_both_180'])} ({pct(h['oos']['breach'])}) | {pct(h['all']['pass_both_180'])} | "
              f"{pct(m['pass_both_180'])} | {pct(m['breach'])} | {num(m['median_days_funded'])} | {pct(m['stalled_buffer'])} | {num(m['median_trades'])} |")
FU = {(p.stem.split('-')[1], p.stem.split('-')[2]): json.loads(p.read_text(encoding='utf-8')) for p in sorted(R.glob('FU-*.json'))}
if FU:
    usd = lambda v: '–' if v is None else f'${v:,.0f}'  # noqa: E731
    md += ['', '## Funded $100k (FTMO First Payout income model: 80% split, reward every 14 days, re-based)', '',
           '| Candidate | Risk | MC income / month while trading | MC median days until it ends | MC breach / frozen | MC total income median / mean | History income / month | History median days to end | Trades / month |',
           '|---|---|---:|---:|---:|---:|---:|---:|---:|']
    for k, v in FU.items():
        m, h = v['mc'], v['hist']; n = m['n']; e = m['ends']
        md.append(f"| {LABEL[k[0]]} | {k[1]}% | {usd(m['pooled_income_per_alive_month'])} | {num(m['median_days_to_end']) if m['median_days_to_end'] else '> ' + str(m['horizon_days'])} | "
                  f"{pct(e.get('breach', 0) / n)} / {pct(e.get('frozen', 0) / n)} | {usd(m['income_total_median'])} / {usd(m['income_total_mean'])} | "
                  f"{usd(h['pooled_income_per_alive_month'])} | {num(h['median_days_to_end']) if h['median_days_to_end'] else '> ' + str(h['horizon_days'])} | {m['trades_per_month_alive_median']} |")
(R / 'RESULTS.md').write_text('\n'.join(md) + '\n', encoding='utf-8'); (R / 'CHOICE.json').write_text(json.dumps(choice, indent=1), encoding='utf-8')
print('\n'.join(md)); print(json.dumps(choice, indent=1))
