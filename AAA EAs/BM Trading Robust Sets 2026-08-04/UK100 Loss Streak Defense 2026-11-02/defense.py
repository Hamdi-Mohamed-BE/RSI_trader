"""UK100 (FTSE 100) vs QuantLab "UK100 3x Drop Monday Pullback" (owner 2026-11-02: "try the same with ... uk100 monday pullback").
QuantLab's public page: UK100 H1, three rules (post-drop rebound, Monday dip, trend pullback) + "loss streak defense and limits", 0.75% risk,
+312.9% since 2017, win 50.8%, PF 1.27, DD -12.03%, 1,908 trades (3.8/week), worst day -3.03%. Rule details are paywalled.

Our evidence already covers the three setups: `FTSE Three Setup Raw 2026-10-27` (the clip's bot, REJECTED) and `FTSE Three Setup Pipeline
2026-10-27` (915 development configs, frozen optimised version REJECTED_AT_VALIDATION). The one QuantLab element never tested is the
loss-streak defense. It is a sizing rule, so it is replayed exactly on the two native Model 4 ledgers (R per trade from the 0.75% budget at
entry, compounding re-sized by the rule). Rules declared here before any result:
  D0 none | D1 after 3 straight losses risk x0.5 until a win | D2 after 2 losses x0.5 until a win | D3 after 3 losses skip the next 3 trades
  D4 after 4 losses x0.25 until a win | D5 x0.5 after 3 losses and x0.25 after 5, until a win
Split (data_split.py, as the FTSE pipeline): development 2019-08-01 -> 2023-10-27, validation -> 2024-10-27, OOS -> 2026-10-27 (all viewed
before; retrospective). python defense.py -> RESULTS.md / RESULTS.json
"""
import gzip, json
from datetime import datetime, timedelta
from pathlib import Path

R = Path(__file__).resolve().parent; B = R.parent
RISK, DEP = 0.0075, 10000.0
SEG = {'Development 2019-23': ('2019-08-01', '2023-10-27'), 'Validation 2023-24': ('2023-10-27', '2024-10-27'),
       'OOS 2024-26': ('2024-10-27', '2026-10-27'), 'All 2019-26': ('2019-08-01', '2026-10-27')}
RULES = {'D0': 'none', 'D1': 'x0.5 after 3 losses until a win', 'D2': 'x0.5 after 2 losses until a win', 'D3': 'skip 3 trades after 3 losses',
         'D4': 'x0.25 after 4 losses until a win', 'D5': 'x0.5 after 3, x0.25 after 5, until a win'}


def ledger(kind):
    if kind == 'optimised':
        r = json.loads((B / 'FTSE Three Setup Pipeline 2026-10-27/native/full-m4/results.json').read_text(encoding='utf-8'))[0]['trades']
        t = [dict(open=datetime.fromisoformat(x['open_time']), close=datetime.fromisoformat(x['close_time']), net=x['net_profit']) for x in r]
    else:
        r = json.loads(gzip.decompress((B / 'FTSE Three Setup Raw 2026-10-27/native/nw-UK100-ALL-max/trades.json.gz').read_bytes()))
        t = [dict(open=datetime.fromisoformat(x['open_time']), close=datetime.fromisoformat(x['close_time']), net=x['net_profit']) for x in r]
    t.sort(key=lambda x: x['close']); bal = DEP
    for x in t: x['R'] = x['net'] / (RISK * bal); bal += x['net']      # R relative to the 0.75% budget at the time
    return [x for x in t if x['open'] >= datetime(2019, 8, 1)]


def replay(trades, rule):
    bal, streak, skip, out = DEP, 0, 0, []
    for x in trades:
        mult = 1.0
        if rule == 'D1' and streak >= 3: mult = 0.5
        if rule == 'D2' and streak >= 2: mult = 0.5
        if rule == 'D4' and streak >= 4: mult = 0.25
        if rule == 'D5': mult = 0.25 if streak >= 5 else 0.5 if streak >= 3 else 1.0
        if rule == 'D3' and skip > 0:
            skip -= 1; streak = 0 if x['R'] > 0 else streak; continue      # skipped trade: the streak still resets on a (missed) win
        pnl = bal * RISK * mult * x['R']; b0 = bal; bal += pnl
        out.append(dict(x, b0=b0, b1=bal, pnl=pnl, mult=mult))
        streak = streak + 1 if x['R'] < 0 else 0
        if rule == 'D3' and streak >= 3: skip = 3; streak = 0
    return out


def stats(rows, a, b):
    A, Bd = datetime.fromisoformat(a), datetime.fromisoformat(b); ts = [x for x in rows if A <= x['open'] < Bd]
    days = (Bd - A).days; wk = sum(1 for i in range(days) if (A + timedelta(days=i)).weekday() < 5)
    p = [x['pnl'] for x in ts]; gp, gl = sum(v for v in p if v > 0), -sum(v for v in p if v < 0)
    if not ts: return dict(n=0)
    peak = bal = ts[0]['b0']; dd = 0.0
    for x in ts: bal = x['b1']; peak = max(peak, bal); dd = max(dd, (peak - bal) / peak * 100)
    return dict(n=len(ts), per_month=round(len(ts) / (days / 30.4375), 2), per_week=round(len(ts) / (days / 7), 2), per_day=round(len(ts) / wk, 3),
                win=round(100 * sum(v > 0 for v in p) / len(p), 1), pf=round(gp / gl, 2) if gl else None,
                ret=round((ts[-1]['b1'] / ts[0]['b0'] - 1) * 100, 1), dd=round(dd, 1))


out = {}
for kind in ('raw (clip bot, ALL)', 'optimised (frozen pipeline final)'):
    t = ledger('raw' if kind.startswith('raw') else 'optimised')
    for rule in RULES:
        rows = replay(t, rule); out[f'{kind}|{rule}'] = {s: stats(rows, *w) for s, w in SEG.items()}
md = ['# UK100 loss-streak defense replay (generated by defense.py)', '',
      'Exact re-sizing of the native Model 4 ledgers (UK100 H1, 0.75% risk, $10k). Rules declared before any result. All parts previously viewed.', '',
      '| Bot | Defense | Development 2019-23 return / PF / DD | Validation 2023-24 | OOS 2024-26 | All 2019-26 return / PF / win / DD | Trades (/month, /week, /day) |',
      '|---|---|---:|---:|---:|---:|---:|']
for k, v in out.items():
    kind, rule = k.split('|'); d, va, o, a = (v[s] for s in SEG)
    cell = lambda x: f"{x['ret']:+}% / {x['pf']} / {x['dd']}%" if x.get('n') else '–'  # noqa: E731
    md.append(f"| {kind} | {rule}: {RULES[rule]} | {cell(d)} | {cell(va)} | {cell(o)} | {a['ret']:+}% / {a['pf']} / {a['win']}% / {a['dd']}% | {a['n']} ({a['per_month']}, {a['per_week']}, {a['per_day']}) |")
(R / 'RESULTS.md').write_text('\n'.join(md) + '\n', encoding='utf-8'); (R / 'RESULTS.json').write_text(json.dumps(out, indent=1), encoding='utf-8')
print('\n'.join(md))
