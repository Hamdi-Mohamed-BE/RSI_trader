"""3 Way Gold vs QuantLab Q4 structure: segments, the frozen PLAN.md choice rule, yearly table, Monte Carlo. -> RESULTS.md / RESULTS.json
python analyse.py"""
import gzip, json, random
from collections import defaultdict
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent; DEP, RISK = 10000.0, 0.0075
SEG = {'dev': ('2019-06-01', '2023-11-01'), 'val': ('2023-11-01', '2024-11-01'), 'oos': ('2024-11-01', '2026-11-01'),
       'last12': ('2025-11-01', '2026-11-01'), 'all': ('2019-06-01', '2026-11-01')}
LABEL = {'dev': 'Development 2019-23', 'val': 'Validation 2023-24', 'oos': 'OOS 2024-26', 'last12': 'Last 12 months', 'all': 'All 2019-26'}
VAR = {'G0': 'production (breakout all year, M15)', 'G1': 'breakout Q4 only, M15', 'G2': 'breakout Q4 only, H1 (QuantLab structure)',
       'G3': 'breakout all year, H1', 'G4': 'breakout OFF'}


def load(k):
    d = ROOT / 'native' / f'nw-XAUUSD-{k}-full'; meta = json.loads((d / 'run.json').read_text())
    t = json.loads(gzip.decompress((d / 'trades.json.gz').read_bytes()))
    for x in t: x['open'] = datetime.fromisoformat(x['open_time']); x['close'] = datetime.fromisoformat(x['close_time'])
    t.sort(key=lambda x: x['close']); bal = DEP
    for x in t: x['R'] = x['net_profit'] / (RISK * bal); x['b0'] = bal; bal += x['net_profit']; x['b1'] = bal
    return meta, t


def seg(t, a, b):
    A, Bd = datetime.fromisoformat(a), datetime.fromisoformat(b); ts = [x for x in t if A <= x['open'] < Bd]
    days = (Bd - A).days; wk = sum(1 for i in range(days) if (A + timedelta(days=i)).weekday() < 5)
    p = [x['net_profit'] for x in ts]; gp, gl = sum(v for v in p if v > 0), -sum(v for v in p if v < 0)
    b0 = ts[0]['b0'] if ts else DEP; peak = bal = b0; dd = 0.0
    for x in ts: bal += x['net_profit']; peak = max(peak, bal); dd = max(dd, (peak - bal) / peak * 100)
    ret = round((bal / b0 - 1) * 100, 1)
    return dict(n=len(ts), per_month=round(len(ts) / (days / 30.4375), 2), per_week=round(len(ts) / (days / 7), 2), per_day=round(len(ts) / wk, 3),
                win=round(100 * sum(v > 0 for v in p) / len(p), 1) if p else None, pf=round(gp / gl, 3) if gl else None, ret=ret, dd=round(dd, 1),
                score=round(ret / max(dd, 0.1), 3))


def years(t):
    out = {}
    for y in range(2019, 2027):
        ts = [x for x in t if x['open'].year == y]
        if ts: out[y] = round((ts[-1]['b1'] / ts[0]['b0'] - 1) * 100, 1)
    return out


def mc(t, paths=2000, seed=20261102):
    start = datetime(2019, 6, 3); blocks = defaultdict(list)
    for x in t: blocks[(x['close'] - start).days // 28].append(x['R'])
    keys = sorted(blocks); allb = [blocks.get(i, []) for i in range(keys[0], keys[-1] + 1)]
    rng = random.Random(seed); rets, dds = [], []
    for _ in range(paths):
        bal = peak = 1.0; dd = 0.0
        for _ in range(13):
            for r in rng.choice(allb): bal *= 1 + r * RISK; peak = max(peak, bal); dd = max(dd, 1 - bal / peak)
        rets.append(bal - 1); dds.append(dd)
    q = lambda v, p: round(100 * sorted(v)[int(p * (len(v) - 1))], 1)  # noqa: E731
    return dict(p_loss_year=round(sum(r < 0 for r in rets) / paths, 3), ret_p10=q(rets, .1), ret_p50=q(rets, .5), ret_p90=q(rets, .9),
                dd_p50=q(dds, .5), dd_p95=q(dds, .95))


runs = {k: load(k) for k in VAR}
stats = {k: {s: seg(t, *w) for s, w in SEG.items()} for k, (m, t) in runs.items()}
elig = [k for k in VAR if (stats[k]['dev']['pf'] or 0) >= 1.15 and stats[k]['dev']['n'] >= 200]
pick = max(elig, key=lambda k: stats[k]['dev']['score']) if elig else None
verdict = None if not pick else ('PASS_VALIDATION' if stats[pick]['val']['ret'] > 0 else 'REJECTED_AT_VALIDATION')
mcs = {k: mc(runs[k][1]) for k in {'G0', pick} if k}
md = ['# 3 Way Gold vs QuantLab "3x Speed Q4 Turn" structure (generated by analyse.py)', '',
      'XAUUSD, native MT5 Model 4, 0.75% risk per module trade, $10k, 150 ms, recorded costs, entries from 2019-06-01. Research copy parity: '
      '92 / 92 trades identical to the production EX5 over 2025-11 → 2026-11. Nothing here is untouched (3WG was fitted on 2021-09 → 2026-09).', '',
      f'**Pick (dev return ÷ closed DD, PF ≥ 1.15, ≥ 200 trades):** {pick} → **{verdict}**' if pick else '**No variant met the development rule.**', '',
      '| Variant | Dev return / PF / DD / n | Val return / PF | OOS return / PF / DD | All 2019-26 return / PF / win / DD | Trades /month, /week, /day | Native net / PF / eq DD |',
      '|---|---:|---:|---:|---:|---:|---:|']
for k in VAR:
    s = stats[k]; d, v, o, a = s['dev'], s['val'], s['oos'], s['all']; nm = runs[k][0]['metrics']
    md.append(f"| {'**' + k + '**' if k == pick else k} {VAR[k]} | {d['ret']:+}% / {d['pf']} / {d['dd']}% / {d['n']} | {v['ret']:+}% / {v['pf']} | "
              f"{o['ret']:+}% / {o['pf']} / {o['dd']}% | {a['ret']:+}% / {a['pf']} / {a['win']}% / {a['dd']}% | {a['per_month']}, {a['per_week']}, {a['per_day']} | "
              f"{nm['return_pct']:+}% / {nm['profit_factor']} / {nm['max_drawdown_pct']}% |")
md += ['', '| Year | ' + ' | '.join(map(str, years(runs['G0'][1]))) + ' |', '|---|' + '---:|' * len(years(runs['G0'][1]))]
for k in VAR:
    y = years(runs[k][1]); md.append(f'| {k} | ' + ' | '.join(f"{y.get(yr, 0):+}%" for yr in years(runs['G0'][1])) + ' |')
md += ['', '| Monte Carlo 1 year x 2,000 (4-week blocks) | P(losing year) | Return p10 / median / p90 | Closed DD median / p95 |', '|---|---:|---:|---:|']
for k, m in mcs.items(): md.append(f"| {k} | {m['p_loss_year']:.0%} | {m['ret_p10']}% / {m['ret_p50']}% / {m['ret_p90']}% | {m['dd_p50']}% / {m['dd_p95']}% |")
md += ['', 'QuantLab public claim (rules unpublished): +210.1% since 2019, PF 1.26, DD −14.09%, 1,309 trades (3.2/week).']
(ROOT / 'RESULTS.md').write_text('\n'.join(md) + '\n', encoding='utf-8')
(ROOT / 'RESULTS.json').write_text(json.dumps(dict(stats=stats, pick=pick, verdict=verdict, monte_carlo=mcs), indent=1), encoding='utf-8')
print('\n'.join(md))
