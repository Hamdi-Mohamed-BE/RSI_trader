"""Owner 2026-11-02: compare the website version, the current (previous production, 0.60% stop) version and the new ATR6 version.
Website = the published caches before this deployment (same 0.60% settings as current, windows end 2026-09-25).
Current / New = native MT5 Model 4 runs of the exact SETs, same windows ending 2026-11-01, plus October 2026 and the 2019-26 study.
python compare.py -> COMPARE.md / COMPARE.json"""
import gzip, json
from datetime import date, datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent; B = ROOT.parent
NATIVE = B / 'Nasdaq 5M Wide Stop Pipeline 2026-11-02' / 'native'
WEB = ROOT / 'before' / 'EA store' / 'data' / 'evidence-cache' / 'v1' / 'products' / 'nasdaq-5m-candle-momentum' / 'dynamic'
PERIODS = ['oct', '6m', '1y', '3y', '5y']


def row(trades, metrics, start, end, quality):
    trades = sorted(trades, key=lambda x: x['close_time']); days = (end - start).days
    weekdays = sum(1 for i in range(days) if (start + timedelta(days=i)).weekday() < 5)
    bal = peak = 10000.0; cdd = 0.0
    for x in trades: bal += x['net_profit']; peak = max(peak, bal); cdd = max(cdd, (peak - bal) / peak * 100)
    g = sum(x['gross_profit'] for x in trades); c = sum(x['commission'] for x in trades); s = sum(x['swap'] for x in trades)
    return dict(window=f'{start} to {end - timedelta(days=1)}', ret=metrics['return_pct'], pf=metrics['profit_factor'], win=metrics['win_rate_pct'],
                n=len(trades), per_month=round(len(trades) / (days / 30.4375), 2), per_week=round(len(trades) / (days / 7), 2),
                per_day=round(len(trades) / weekdays, 3), eq_dd=metrics['max_drawdown_pct'], closed_dd=round(cdd, 2),
                gross=round(g, 2), commission=round(c, 2), swap=round(s, 2), net=round(g + c + s, 2), sharpe=metrics.get('sharpe_ratio'), quality=quality)


def native(case):
    d = NATIVE / case
    if not (d / 'run.json').exists(): return None
    m = json.loads((d / 'run.json').read_text()); t = json.loads(gzip.decompress((d / 'trades.json.gz').read_bytes()))
    s = datetime.strptime(m['start'], '%Y.%m.%d').date(); e = datetime.strptime(m['end_exclusive'], '%Y.%m.%d').date()
    return row(t, m['metrics'], s, e, m['metrics']['history_quality'])


def website(period):
    p = WEB / f'{period}.json'
    if not p.exists(): return None
    c = json.loads(p.read_text(encoding='utf-8-sig')); t = json.loads((WEB / f'{period}.trades.json').read_text(encoding='utf-8-sig'))
    s = date.fromisoformat(c['stats']['from']); e = date.fromisoformat(c['stats']['to'])
    return row(t, c['stats'], s, e, c['stats']['history_quality'])


cases = {'Website (0.60% stop, published, to 2026-09-25)': {p: website(p) for p in PERIODS},
         'Current (0.60% stop, same windows to 2026-11-01)': {p: native(f'nw-USTEC-CURRENT-{p}') for p in PERIODS},
         'New (ATR14 x6 stop, to 2026-11-01)': {p: native(f'nw-USTEC-{"A6_M1_DION_M4" if p == "oct" else "DEPLOY"}-{p}') for p in PERIODS}}
conf = json.loads((B / 'Nasdaq 5M Wide Stop Pipeline 2026-11-02' / 'CONFIRM.json').read_text())
LABEL = {'oct': 'October 2026', '6m': '6 months', '1y': '1 year', '3y': '3 years', '5y': '5 years'}
md = ['# Nasdaq 5M: website vs current vs new (generated by compare.py)', '',
      'Native MT5 Model 4, USTEC M5, $10k, 1% risk, 150 ms, recorded commission and swap (spread inside the fills). Website = the caches the '
      'site published before 2026-11-02 (same 0.60% settings as Current, older windows). Equity DD = MT5 maximal; closed DD from the trade list.', '']
for p in PERIODS:
    md += [f'## {LABEL[p]}', '| Version | Window | Return | PF | Win % | Trades | /month | /week | /day | Equity DD | Closed DD | Gross | Commission | Swap | Net | Ticks |',
           '|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|']
    for name, rows in cases.items():
        r = rows[p]
        if r is None:
            md.append(f'| {name} | {"no separate October run: same settings as Current" if p == "oct" and name.startswith("Website") else "not run"} |' + ' |' * 14); continue
        md.append(f"| {name} | {r['window']} | {r['ret']:+.2f}% | {r['pf']} | {r['win']}% | {r['n']} | {r['per_month']} | {r['per_week']} | {r['per_day']} | "
                  f"{r['eq_dd']}% | {r['closed_dd']}% | {r['gross']:+,.0f} | {r['commission']:,.0f} | {r['swap']:,.0f} | {r['net']:+,.0f} | {r['quality']} |")
    md.append('')
md += ['## Full 2019-2026 study (Model 4, entries by part)', '| Part | Current: return / PF / closed DD / trades | New: return / PF / closed DD / trades |', '|---|---:|---:|']
for s, lab in (('dev', 'Development 2019-23'), ('val', 'Validation 2023-24'), ('oos', 'OOS 2024-26'), ('last12', 'Last 12 months'), ('all', 'All 2019-26')):
    a, b = conf['P060_M1_DION']['m4'][s], conf['A6_M1_DION']['m4'][s]
    md.append(f"| {lab} | {a['ret']:+}% / {a['pf']} / {a['dd']}% / {a['n']} | {b['ret']:+}% / {b['pf']} / {b['dd']}% / {b['n']} |")
ya, yb = conf['P060_M1_DION']['years_m4'], conf['A6_M1_DION']['years_m4']
md += ['', '| Year | ' + ' | '.join(ya) + ' |', '|---|' + '---:|' * len(ya), '| Current | ' + ' | '.join(f'{v:+}%' for v in ya.values()) + ' |',
       '| New | ' + ' | '.join(f'{yb[k]:+}%' for k in ya) + ' |']
ma, mb = conf['P060_M1_DION']['mc_m4'], conf['A6_M1_DION']['mc_m4']
md += ['', '| Monte Carlo, 1 year x 2,000 (4-week blocks of 2019-26) | Current | New |', '|---|---:|---:|',
       f"| P(losing year) | {ma['p_loss_year']:.0%} | {mb['p_loss_year']:.0%} |", f"| Return p10 / median / p90 | {ma['ret_p10']}% / {ma['ret_p50']}% / {ma['ret_p90']}% | {mb['ret_p10']}% / {mb['ret_p50']}% / {mb['ret_p90']}% |",
       f"| Closed DD median / p95 | {ma['dd_p50']}% / {ma['dd_p95']}% | {mb['dd_p50']}% / {mb['dd_p95']}% |"]
(ROOT / 'COMPARE.md').write_text('\n'.join(md) + '\n', encoding='utf-8')
(ROOT / 'COMPARE.json').write_text(json.dumps(cases, indent=1), encoding='utf-8')
print('\n'.join(md))
