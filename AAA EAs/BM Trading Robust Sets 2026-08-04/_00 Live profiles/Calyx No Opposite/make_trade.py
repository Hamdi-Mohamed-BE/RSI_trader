"""Generate CNO_Trade.mqh = the isolated MetaEditor's standard Trade/Trade.mqh with ONLY these asserted edits:
  - its relative includes point at <Trade/...> (the file lives next to the EA sources, not in Include/Trade)
  - CTrade::OrderSend sends through CalyxNoOppOrderSend (async flag kept), which is the old ::OrderSend / ::OrderSendAsync path while
    InpCalyxNoOpposite=false
  - #include "CalyxNoOpposite.mqh" at the top
python make_trade.py   (writes CNO_Trade.mqh + CNO.json with the hashes)"""
import hashlib, json
from pathlib import Path

H = Path(__file__).resolve().parent; B = H.parents[1]
STD = B / '_Backtests/MT5-DMC-20260811/MQL5/Include/Trade/Trade.mqh'


def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def main():
    raw = STD.read_bytes(); text = raw.decode('utf-8-sig') if not raw.startswith(b'\xff\xfe') else raw.decode('utf-16')
    edits = [('#include "OrderInfo.mqh"', '#include <Trade/OrderInfo.mqh>'), ('#include "HistoryOrderInfo.mqh"', '#include <Trade/HistoryOrderInfo.mqh>'),
             ('#include "PositionInfo.mqh"', '#include <Trade/PositionInfo.mqh>'), ('#include "DealInfo.mqh"', '#include <Trade/DealInfo.mqh>'),
             ('res=::OrderSendAsync(request,result);', 'res=CalyxNoOppOrderSend(request,result,true);'),
             ('res=::OrderSend(request,result);', 'res=CalyxNoOppOrderSend(request,result,false);'),
             ('#include <Object.mqh>', '#include "CalyxNoOpposite.mqh"   // Calyx No Opposite 2026-11-17 (generated by make_trade.py)\n#include <Object.mqh>')]
    for a, b in edits:
        assert text.count(a) == 1, (a, text.count(a)); text = text.replace(a, b)
    out = H / 'CNO_Trade.mqh'; out.write_bytes(text.encode('utf-8'))
    (H / 'CNO.json').write_text(json.dumps(dict(standard_trade=str(STD), standard_sha256=sha(STD), cno_trade_sha256=sha(out), cno_include_sha256=sha(H / 'CalyxNoOpposite.mqh')), indent=2) + '\n', encoding='utf-8')
    print('written', out, sha(out)[:12])


if __name__ == '__main__':
    main()
