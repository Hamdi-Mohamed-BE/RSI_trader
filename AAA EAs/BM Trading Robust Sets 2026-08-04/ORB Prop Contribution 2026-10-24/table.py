"""RESULTS.md from the RESULT-orbx-*.json files (python table.py)."""
import json
from pathlib import Path

R = Path(__file__).resolve().parent
SHORT = {'us100-h1-orb-13utc': 'US100 H1 13UTC', 'us100-orb-new-york-m30': 'US100 NY M30', 'us100-selective-orb-v3': 'US100 Selective V3',
         'xau-orb-new-york-m30': 'XAU NY M30', 'xau-orb-london-ny-overlap-m30': 'XAU London-NY M30'}
pct = lambda v: '-' if v is None else f'{100 * v:.0f}%'  # noqa: E731
num = lambda v: '-' if v is None else f'{v:g}'  # noqa: E731
usd = lambda v: '-' if v is None else f'${v:,.0f}'  # noqa: E731


def load(base, v, part):
    f = R / f"RESULT-orbx-{base}-{v.replace(' ', '_')}-0.50-{part}.json"
    return json.loads(f.read_text(encoding='utf-8')) if f.exists() else None


md = ['# ORB contribution to prop results (generated by table.py)', '',
      'Frozen Portfolio Prop Comparison 2026-10-22 engine, FTMO 2-step at $100k, 0.5% risk (packaged), guard on. Only the member list changes.',
      'Challenge = both phases within 180 days of purchase; MC = 2,000 paths, hist = every weekday start. Funded = 36-month MC, 80% split.',
      '"minus X" removes that ORB. Higher pass / fewer days / more income without an ORB means that ORB hurts the prop result.', '']
for base, label in (('ftmo', 'FTMO guarded · Current 14 + ORB (17 EAs incl. 3 Way Gold modules)'), ('prop-ready', 'Prop ready (9 EAs)')):
    md += [f'## {label}', '', '| Members | Pass both ≤180 d MC / hist | Funded ≤90 d MC / hist | Breach | Stuck at buffer MC | Median days to funded MC / hist | '
           'Funded income / month (median, MC) | Median days funded lasts | Funded total income (median) | Challenge trades (median) | Funded trades / month |',
           '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
    for v in ['ALL', 'NO_ORBS'] + [f'minus {o}' for o in SHORT]:
        c, f = load(base, v, 'challenge'), load(base, v, 'funded')
        name = 'All (current)' if v == 'ALL' else 'No ORBs' if v == 'NO_ORBS' else 'without ' + SHORT[v[6:]]
        if not c: md.append(f'| {name} | pending |'); continue
        m, h = c['mc'], c['hist']; fm = f['mc'] if f else {}
        md.append(f"| {name} | {pct(m['pass_both_180'])} / {pct(h['pass_both_180'])} | {pct(m['funded_90'])} / {pct(h['funded_90'])} | {pct(m['breach'])} | {pct(m['stalled_buffer'])} | "
                  f"{num(m['median_days_funded'])} / {num(h['median_days_funded'])} | {usd(fm.get('monthly_income_while_alive_median'))} | {num(fm.get('median_days_to_end'))} | "
                  f"{usd(fm.get('income_total_median'))} | {num(m['median_trades'])} | {num(fm.get('trades_per_month_alive_median'))} |")
    md.append('')
(R / 'RESULTS.md').write_text('\n'.join(md) + '\n', encoding='utf-8'); print('RESULTS.md')
