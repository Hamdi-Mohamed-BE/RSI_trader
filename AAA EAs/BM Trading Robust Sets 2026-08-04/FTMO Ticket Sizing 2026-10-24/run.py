"""'Price the eval like a ticket' test (owner-pasted clip, 2026-10-24) on our FTMO portfolios.
Frozen Portfolio Prop Comparison 2026-10-22 engine (FTMO 2-step, $100k, 180-day attempt), risk 0.5-3% per trade.
For each config: pass rate p, attempt length (pass: days to both phases; breach: days to breach; otherwise 180),
expected fees per funded account = 1/p (one-time-fee firm), expected days to funded with retries = E[attempt days]/p,
expected fee-months = E[attempt months]/p (monthly-fee firm). Independent MC attempts. Python only.
python run.py all | table
"""
import importlib.util, json, random, statistics, sys
from concurrent.futures import ProcessPoolExecutor
from datetime import date, datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

R = Path(__file__).resolve().parent; B = R.parent; SRC = B / 'Portfolio Prop Comparison 2026-10-22'
Z = ZoneInfo('Europe/Prague')
RISKS = {'0.50': .005, '1.00': .01, '1.50': .015, '2.00': .02, '3.00': .03}
SLUGS = ['ftmo', 'current14-orb05', 'prop-ready', 'best-prop']


def engine():
    s = importlib.util.spec_from_file_location('compare', SRC / 'compare.py'); c = importlib.util.module_from_spec(s); s.loader.exec_module(c); return c


def attempt(c, plan, basket, guard, r, d, ev):
    m = c.Challenge(plan, basket, c.P.start_dict(d, c.P.HORIZON), guard, r); t = c.P.drive(m, ev).result(); x = c.T.per_trial(t)
    passed = bool(x['both']) and not x['breach']
    if passed: days = x['both']
    elif x['breach']:
        fe = [p.get('fail_epoch') for p in (t.get('phase1') or {}, t.get('phase2') or {}) if p and p.get('fail_epoch')]
        days = (datetime.fromtimestamp(min(fe), Z).date() - datetime.fromtimestamp(t['start_epoch'], Z).date()).days + 1 if fe else c.P.HORIZON
    else: days = c.P.HORIZON
    return dict(passed=passed, breach=x['breach'], stalled=x['buffer'], days=days, funded=x['funded'], trades=x['trades'])


def summarise(rows):
    n = len(rows); p = sum(r['passed'] for r in rows) / n; att = statistics.fmean(r['days'] for r in rows)
    win = [r['days'] for r in rows if r['passed']]
    return dict(n=n, pass_rate=round(p, 4), breach=round(sum(r['breach'] for r in rows) / n, 4), stalled=round(sum(r['stalled'] for r in rows) / n, 4),
                median_days_to_pass=statistics.median(win) if win else None, mean_attempt_days=round(att, 1),
                fees_per_funded=round(1 / p, 2) if p else None, days_to_funded_with_retries=round(att / p, 1) if p else None,
                fee_months_per_funded=round(att / 30.4375 / p, 2) if p else None, median_trades=statistics.median(r['trades'] for r in rows))


def job(args):
    slug, risk = args; c = engine(); cfg = c.PORTFOLIOS[slug]; r = RISKS[risk]
    data, plan, events, epochs = c.setup(cfg['stream']); pool, mondays, index, priority = c.mc_pool(data, plan); sd = date(2030, 1, 7)
    hist = []; d = c.P.DATA_START
    while d + timedelta(days=c.P.HORIZON) <= c.P.DATA_END:
        if d.weekday() < 5: hist.append(attempt(c, plan, cfg['basket'], cfg['guard'], r, d, c.P.window(events, epochs, c.P.midnight(d), c.P.midnight(d + timedelta(days=c.P.HORIZON)))))
        d += timedelta(days=1)
    rng = random.Random(c.T.SEED); mc = [attempt(c, plan, cfg['basket'], cfg['guard'], r, sd, c.T.bootstrap_events(pool, mondays, index, rng, sd, priority)) for _ in range(c.T.PATHS)]
    out = dict(portfolio=slug, label=cfg['label'], risk=r, guard=cfg['guard'], hist=summarise(hist), mc=summarise(mc))
    (R / f'RESULT-{slug}-{risk}.json').write_text(json.dumps(out, indent=1), encoding='utf-8'); return f'{slug} {risk} MC pass {out["mc"]["pass_rate"]} fees {out["mc"]["fees_per_funded"]} days {out["mc"]["days_to_funded_with_retries"]}'


def table():
    pct = lambda v: '-' if v is None else f'{100 * v:.0f}%'  # noqa: E731
    num = lambda v: '-' if v is None else f'{v:g}'  # noqa: E731
    md = ['# FTMO ticket sizing (generated by run.py table)', '', 'FTMO 2-step $100k, 180-day attempts, frozen Prop Comparison engine. MC = 2,000 independent attempts; hist = every weekday start.',
          'Fees per funded = 1 / pass rate (FTMO charges once per attempt). Days to funded with retries = mean attempt length / pass rate.',
          'Fee-months = the same in 30-day months (what a monthly-fee firm would bill). Guards above 0.5% are hypothetical (installers cap at 0.5%).', '',
          '| Portfolio | Risk | Pass MC / hist | Breach MC | Stuck at buffer MC | Median days to pass MC | Mean attempt days MC | Fees per funded MC / hist | Days to funded incl. retries MC / hist | Fee-months per funded MC | Median trades / attempt |',
          '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
    for slug in SLUGS:
        for risk in RISKS:
            f = R / f'RESULT-{slug}-{risk}.json'
            if not f.exists(): continue
            d = json.loads(f.read_text(encoding='utf-8')); m, h = d['mc'], d['hist']
            md.append(f"| {d['label']} | {risk}% | {pct(m['pass_rate'])} / {pct(h['pass_rate'])} | {pct(m['breach'])} | {pct(m['stalled'])} | {num(m['median_days_to_pass'])} | {m['mean_attempt_days']} | "
                      f"{num(m['fees_per_funded'])} / {num(h['fees_per_funded'])} | {num(m['days_to_funded_with_retries'])} / {num(h['days_to_funded_with_retries'])} | {num(m['fee_months_per_funded'])} | {num(m['median_trades'])} |")
    (R / 'RESULTS.md').write_text('\n'.join(md) + '\n', encoding='utf-8'); print('RESULTS.md')


if __name__ == '__main__':
    if sys.argv[1] == 'table': table(); sys.exit()
    jobs = [(s, r) for s in SLUGS for r in RISKS]; jobs.sort(key=lambda j: j[0] not in ('ftmo', 'current14-orb05'))
    with ProcessPoolExecutor(max_workers=6) as ex:
        for line in ex.map(job, jobs): print(line, flush=True)
    table()
