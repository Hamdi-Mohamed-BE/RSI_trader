"""RESULTS.md: rank single-EA FTMO configs by DEVELOPMENT MC P(both phases <= 30 d), then show val / OOS / all. python table.py"""
import json
from pathlib import Path

R = Path(__file__).resolve().parent
d = json.loads((R / 'RESULTS.json').read_text(encoding='utf-8'))
rows = [r for r in d['results'].values() if r['dev_mc']]
pct = lambda v: '-' if v is None else f'{100 * v:.1f}%'  # noqa: E731
key = lambda r: (r['dev_mc']['both_30'], -r['dev_mc']['breach_30'])  # noqa: E731
cand = sorted((r for r in rows if not r['news']), key=key, reverse=True)
news = sorted((r for r in rows if r['news']), key=key, reverse=True)
S = d['split']
md = ['# One EA, one month — FTMO $100k 2-step (generated by table.py)', '',
      f"Ranked on DEVELOPMENT ({S['development']['start']} → {S['development']['end_exclusive']}) Monte Carlo only; validation (→ {S['validation']['end_exclusive']}) and OOS (→ {S['oos']['end_exclusive']}) shown after.",
      'Pass in a month = phase 1 (+10%) and phase 2 (+5%, fresh balance from the next Prague midnight) both done ≤ 30 calendar days from the start, ≥ 4 trading days each.',
      'Breach = 5% daily / 10% max loss with every open position marked at its full stop. MC = 1,000 four-week-block paths per window; hist = every weekday start.', '',
      '## Top 12 non-news configurations (picked on development)', '',
      '| # | EA | Risk | Trades / month | / day | Dev MC pass ≤30 d / breach ≤30 d | Val MC pass / breach | OOS MC pass / breach | All-period MC pass / breach | All-period hist pass / breach | Phase 1 ≤30 d (all MC) | Median days to pass (all MC) |',
      '|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
for i, r in enumerate(cand[:12]):
    md.append(f"| {i + 1} | {r['ea']} | {r['risk']:g}% | {r['trades_per_month']} | {r['trades_per_day']} | {pct(r['dev_mc']['both_30'])} / {pct(r['dev_mc']['breach_30'])} | "
              f"{pct(r['val_mc']['both_30'])} / {pct(r['val_mc']['breach_30'])} | {pct(r['oos_mc']['both_30'])} / {pct(r['oos_mc']['breach_30'])} | "
              f"{pct(r['all_mc']['both_30'])} / {pct(r['all_mc']['breach_30'])} | {pct(r['all_hist']['both_30'])} / {pct(r['all_hist']['breach_30'])} | "
              f"{pct(r['all_mc']['p1_30'])} | {r['all_mc']['median_days_both'] or '-'} |")
md += ['', '## Best per EA (all-period MC, any risk) — reference, not a selection', '', '| EA | Best risk | All MC pass ≤30 d | Breach ≤30 d | Hist pass ≤30 d | Trades / month |', '|---|---:|---:|---:|---:|---:|']
best = {}
for r in rows:
    if r['ea'] not in best or r['all_mc']['both_30'] > best[r['ea']]['all_mc']['both_30']: best[r['ea']] = r
for r in sorted(best.values(), key=lambda r: -r['all_mc']['both_30']):
    md.append(f"| {r['ea']}{' (news, not credible)' if r['news'] else ''} | {r['risk']:g}% | {pct(r['all_mc']['both_30'])} | {pct(r['all_mc']['breach_30'])} | {pct(r['all_hist']['both_30'])} | {r['trades_per_month']} |")
(R / 'RESULTS.md').write_text('\n'.join(md) + '\n', encoding='utf-8'); print('RESULTS.md')
