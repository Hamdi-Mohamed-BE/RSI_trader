def load(name):
    p = R / 'native' / name / 'results.json'
    if not p.exists(): return None
    res = json.loads(p.read_text()); bal = 10000.0; out = []
    tr = sorted(res['trades'], key=lambda t: t['close_time'])
    closes = []
    for t in tr:
        op = datetime.fromisoformat(t['open_time']).replace(tzinfo=timezone.utc); cl = datetime.fromisoformat(t['close_time']).replace(tzinfo=timezone.utc)
        before = 10000.0 + sum(x['net_profit'] for x in tr if datetime.fromisoformat(x['close_time']).replace(tzinfo=timezone.utc) <= op)
        out.append(dict(op=op, cl=cl, net=t['net_profit'], r=t['net_profit'] / (0.01 * before)))
    return res, out


def streaks(ts):
    runs = {True: [], False: []}; cur, n = None, 0
    for t in sorted(ts, key=lambda x: x['cl']):
        s = t['net'] > 0
        if s == cur: n += 1
        else:
            if cur is not None: runs[cur].append(n)
            cur, n = s, 1
    if cur is not None: runs[cur].append(n)
    avg = lambda v: round(sum(v) / len(v), 2) if v else 0.0  # noqa: E731
    return dict(avg_win_streak=avg(runs[True]), max_win_streak=max(runs[True], default=0), avg_loss_streak=avg(runs[False]), max_loss_streak=max(runs[False], default=0))


def stats(ts):
    if not ts: return dict(n=0, sumR=0.0, meanR=None, pf=None, win=None, avg_win_streak=0, max_win_streak=0, avg_loss_streak=0, max_loss_streak=0)
    w = sum(t['net'] for t in ts if t['net'] > 0); l = -sum(t['net'] for t in ts if t['net'] < 0)
    return dict(n=len(ts), sumR=round(sum(t['r'] for t in ts), 2), meanR=round(sum(t['r'] for t in ts) / len(ts), 3), pf=round(w / l, 2) if l else None,
                win=round(100 * sum(t['net'] > 0 for t in ts) / len(ts), 1), **streaks(ts))


def windows(ts):
    out = {}
    for k, (a, b) in WIN.items():
        a, b = datetime.fromisoformat(a).replace(tzinfo=timezone.utc), datetime.fromisoformat(b).replace(tzinfo=timezone.utc)
        out[k] = stats([t for t in ts if a <= t['op'] < b])
    return out


def verdict(base, var):
    better = sum(var['w'][k]['sumR'] > base['w'][k]['sumR'] for k in WIN)
    pf_up = (var['all']['pf'] or 0) > (base['all']['pf'] or 0)
    v = 'IMPROVED' if better == 3 and pf_up else 'MIXED' if better == 2 else 'NOT IMPROVED'
    return v + (' (thin <30 trades)' if var['all']['n'] < 30 else ''), better


def ny(t): return t.astimezone(NY)


