"""RESULTS.md from RESULTS.json (python table.py)."""
import json
from pathlib import Path

R = Path(__file__).resolve().parent
d = json.loads((R / 'RESULTS.json').read_text(encoding='utf-8'))['results']
pct = lambda v: '-' if v is None else f'{100 * v:.0f}%'  # noqa: E731
num = lambda v: '-' if v is None else f'{round(v, 1):g}'  # noqa: E731
usd = lambda v: f'${v:,.0f}'  # noqa: E731
md = ['# FTMO Swing — Full EA portfolio · Recommended Adaptive (generated by table.py)', '',
      'Optimistic = breach checked on closed balance; pessimistic = every open position marked at its full stop. Reality is in between.',
      'NO_NEWS = the four News Pulse EAs removed (headline, PLAN Addendum 1). Income = 80% of profit withdrawn every 14 days, 10k account;',
      '20k / 50k / 100k scale linearly (fractional lots). MC = 2,000 challenge / 1,000 funded paths of 4-week blocks; hist = weekday starts.', '']
for variant in ('NO_NEWS', 'ALL36'):
    md += [f'## {variant}', '', '### Challenge (phase 1 = +10%, phase 2 = +5%, 5% daily / 10% max loss, 365 days per phase)', '',
           '| Risk | Breach model | Phase 1 pass MC / hist | Phase 1 breach MC | Phase 1 ≤ 90 d MC | Median days phase 1 | Phase 2 pass (given phase 1) MC / hist | Median days phase 2 | Funded MC / hist | Funded ≤ 90 d / ≤ 180 d MC | Median days to funded MC (p25–p75) / hist | Trades / day |',
           '|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
    for risk in ('0.50', '0.75', '1.00'):
        for model in ('optimistic', 'pessimistic'):
            r = d[f'{variant}|{risk}|{model}']; m, h = r['challenge_mc'], r['challenge_hist']
            md.append(f"| {risk}% | {model} | {pct(m['p1_pass'])} / {pct(h['p1_pass'])} | {pct(m['p1_breach'])} | {pct(m['p1_pass_90'])} | {num(m['p1_days_median'])} | "
                      f"{pct(m['p2_pass_given_p1'])} / {pct(h['p2_pass_given_p1'])} | {num(m['p2_days_median'])} | {pct(m['funded'])} / {pct(h['funded'])} | "
                      f"{pct(m['funded_90'])} / {pct(m['funded_180'])} | {num(m['funded_days_median'])} ({num(m['funded_days_p25'])}–{num(m['funded_days_p75'])}) / {num(h['funded_days_median'])} | {num(m['trades_per_day_p1'])} |")
    md += ['', '### Funded account (3-year horizon; trader share 80%)', '',
           '| Risk | Breach model | Breach ≤ 90 d / 180 d / 1 y / 3 y (MC) | Median days alive MC / hist | Median days to breach (breached paths) | Monthly income 10k median / mean | 20k | 50k | 100k (median) | Total paid 10k median / mean | No payout at all | Trades / day |',
           '|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
    for risk in ('0.50', '0.75', '1.00'):
        for model in ('optimistic', 'pessimistic'):
            r = d[f'{variant}|{risk}|{model}']; f, fh = r['funded_mc'], r['funded_hist']
            mm = f['monthly_median']
            md.append(f"| {risk}% | {model} | {pct(f['breach_90'])} / {pct(f['breach_180'])} / {pct(f['breach_1y'])} / {pct(f['breach_3y'])} | {num(f['days_alive_median'])} / {num(fh['days_alive_median'])} | "
                      f"{num(f['days_to_breach_median_breached'])} | {usd(mm)} / {usd(f['monthly_mean'])} | {usd(2 * mm)} | {usd(5 * mm)} | {usd(10 * mm)} | "
                      f"{usd(f['total_paid_median'])} / {usd(f['total_paid_mean'])} | {pct(f['no_payout'])} | {num(f['trades_per_day'])} |")
    md.append('')
(R / 'RESULTS.md').write_text('\n'.join(md) + '\n', encoding='utf-8'); print('\n'.join(md))
