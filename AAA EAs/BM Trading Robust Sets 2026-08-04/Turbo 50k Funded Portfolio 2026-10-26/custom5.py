"""Owner 2026-10-27: a 5-EA portfolio on the Turbo $50k reward-account rules at 0.5 / 0.75 / 1%:
Nasdaq 5M (DI filter OFF), XAU RSI VWAP, Gold Overnight Value Area, 3 Way Gold, EMA3.
Same numba kernel / firm model / stream construction as sim.py and all_portfolios.py (Nasdaq 5M DI OFF lane from the Best Prop retest stream).
Two guard models: as installed (only per-trade risk) and the Turbo guard (IMPROVE.json profile for that risk).
python custom5.py   -> CUSTOM5.json, CUSTOM5.md
"""
import json
from pathlib import Path
import numpy as np
import sim

R = Path(__file__).resolve().parent; B = R.parent
raw = json.loads(sim.SRC.read_text(encoding='utf-8'))['full-eas']
rows = [(r['op'], r['cl'], r['key'], r['symbol'], r['unit_risk'], r['unit_gross'] + r['unit_comm'] + r['unit_swap'], r.get('risk_weight', 1.))
        for r in raw if r['unit_risk'] > 0 and r['op'] < r['cl'] and not r['key'].startswith('news-pulse')]
for c in json.loads((B / 'Best Prop Portfolio Retest 2026-10-20/INPUTS-DI_OFF.json').read_text(encoding='utf-8'))['candidates']:
    if c['ea'] == 'nasdaq-5m-candle-momentum' and not c['end_censored']:
        rows.append((c['op'], c['cl'], 'nasdaq-5m-di-off', c['symbol'], c['unit_risk'], c['unit_gross'] + c['unit_commission'] + c['unit_swap'], 1.0))
rows.sort(key=lambda r: (r[0], r[1]))
keys = sorted({r[2] for r in rows}); syms = sorted({r[3] for r in rows})
sim.A = dict(op=np.array([r[0] for r in rows]), cl=np.array([r[1] for r in rows]), lane=np.array([keys.index(r[2]) for r in rows], np.int64),
             sym=np.array([syms.index(r[3]) for r in rows], np.int64), ur=np.array([r[4] for r in rows]), un=np.array([r[5] for r in rows]), w=np.array([r[6] for r in rows]))
sim.KEYS, sim.SYMS, sim.NL, sim.NS = keys, syms, len(keys), len(syms)

MEMBERS = ['nasdaq-5m-di-off', 'xau-rsi-vwap', 'gold-overnight-value-area', '3-way-gold', 'ema3']
assert all(m in keys for m in MEMBERS)
RISKS = (0.5, 0.75, 1.0)
imp = json.loads((R / 'IMPROVE.json').read_text(encoding='utf-8'))
NOGUARD = dict(maxopen=1e6, persym=1e6, dstop=1e6, buffer=-1e6, taper=0.0, dcap=0.0)
GUARDS = [('As installed (no guard)', lambda r: NOGUARD), ('Turbo guard', lambda r: imp['risks'][str(r)]['guard'])]
WEEKS3, WEEKS1 = 3 * 364 / 7, 365 / 7


def extra(o):
    br = o[:, 0] == 1; paid = o[:, 3] > 0
    return dict(breach_days_mean=round(float(o[br, 1].mean()), 1) if br.any() else None,
                avg_payout_size=round(float((o[paid, 2] / o[paid, 3]).mean()), 0) if paid.any() else None,
                payouts_mean=round(float(o[:, 3].mean()), 2))


def main():
    mc3 = sim.mc_paths('all', sim.MC_N, 3 * 364, sim.SEED + 1); mc1 = sim.mc_paths('all', sim.MC_N, 365, sim.SEED + 2); hist = sim.hist_paths('all', 365)
    out = {}
    for gname, guard in GUARDS:
        for r in RISKS:
            g = guard(r)
            m3 = sim.simulate(mc3, MEMBERS, r, g, 3 * 364); m1 = sim.simulate(mc1, MEMBERS, r, g, 365); h = sim.simulate(hist, MEMBERS, r, g, 365)
            m3o = sim.simulate(mc3, MEMBERS, r, g, 3 * 364, pess=False)
            out[f'{gname}|{r}'] = dict(guard_model=gname, risk=r, guard=g, mc3=sim.summary(m3, 3 * 364) | extra(m3), mc3_optimistic=sim.summary(m3o, 3 * 364) | extra(m3o),
                                      mc1=sim.summary(m1, 365) | extra(m1), hist1=sim.summary(h, 365) | extra(h))
            s = out[f'{gname}|{r}']['mc3']
            print(gname, r, 'week', round(s['income_total_mean'] / WEEKS3), 'breach', s['breach'], 'freeze', s['freeze'], flush=True)
    (R / 'CUSTOM5.json').write_text(json.dumps(out, indent=1), encoding='utf-8')
    usd = lambda v: '-' if v is None else f'${v:,.0f}'  # noqa: E731
    pct = lambda v: '-' if v is None else f'{100 * v:.0f}%'  # noqa: E731
    num = lambda v: '-' if v is None else f'{v:g}'  # noqa: E731
    md = ['# 5-EA portfolio on the Turbo $50k reward-account rules (generated by custom5.py)', '',
          'Members: Nasdaq 5M Candle Momentum (DI filter OFF), XAU RSI VWAP, Gold Overnight Value Area, 3 Way Gold (3 modules), EMA3.',
          'Python/numba replay of frozen native ledgers 2021-10 → 2026-10, same firm model as sim.py: 3% daily loss of the day-start balance; $3,000 trailing max loss',
          'below the highest closed balance, re-based after each reward; rewards every 14 days if ≥ 3 days of ≥ $250 and best day ≤ 20% of cycle profit; 80% share.',
          'Breach = PESSIMISTIC (every open position at its stop) unless marked optimistic. Payout per week / month = total paid ÷ horizon (accounts that ended earn 0 afterwards).',
          'MC = 1,000 resampled paths (4-week blocks); History = every weekday start 2021-10 → 2025-10, 12 months each. In-sample; backtest income is not a forecast.', '',
          '## Expected payout (trader share)', '',
          '| Guard | Risk | Payout / week 3y MC mean (median) | Payout / week 1y MC mean | Payout / week history 1y mean | Payout / month 3y MC mean | Avg payout size | Payouts in 3y (mean) | No payout ever (3y) |',
          '|---|---:|---:|---:|---:|---:|---:|---:|---:|']
    for v in out.values():
        m, a, h = v['mc3'], v['mc1'], v['hist1']
        md.append(f"| {v['guard_model']} | {v['risk']:g}% | {usd(m['income_total_mean'] / WEEKS3)} ({usd(m['income_total_median'] / WEEKS3)}) | {usd(a['income_total_mean'] / WEEKS1)} | "
                  f"{usd(h['income_total_mean'] / WEEKS1)} | {usd(m['income_total_mean'] / 36)} | {usd(m['avg_payout_size'])} | {m['payouts_mean']} | {pct(m['no_payout'])} |")
    md += ['', '## Full simulation data', '',
           '| Guard | Risk | Breach 3y MC pess / opt | Breach ≤ 1y history | Avg days to breach MC (median) | Frozen 3y | Median days account lasts | First payout day (median) | Worst day MC / history | Worst week MC | Max closed DD median / worst | Worst stop-marked DD | Win / loss streak avg (max) | Trades / month | / day |',
           '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
    for v in out.values():
        m, o, h = v['mc3'], v['mc3_optimistic'], v['hist1']
        md.append(f"| {v['guard_model']} | {v['risk']:g}% | {pct(m['breach'])} / {pct(o['breach'])} | {pct(h['breach_365'])} | {num(m['breach_days_mean'])} ({num(m['days_to_breach_median'])}) | "
                  f"{pct(m['freeze'])} | {num(m['days_alive_median'])} | {num(m['first_payout_day_median'])} | {usd(m['worst_day'])} / {usd(h['worst_day'])} | {usd(m['worst_week'])} | "
                  f"{usd(m['dd_closed_median'])} / {usd(m['dd_closed_worst'])} | {usd(m['dd_stop_worst'])} | {m['win_streak_avg']} / {m['loss_streak_avg']} ({num(m['win_streak_max'])} / {num(m['loss_streak_max'])}) | "
                  f"{h['trades_per_month']} | {h['trades_per_day']} |")
    (R / 'CUSTOM5.md').write_text('\n'.join(md) + '\n', encoding='utf-8'); print('CUSTOM5.md')


if __name__ == '__main__':
    main()
