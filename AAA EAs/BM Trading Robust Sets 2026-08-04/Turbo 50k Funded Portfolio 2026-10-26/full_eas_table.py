"""FULL_EAS_TURBO.json -> FULL_EAS_TURBO.md. python full_eas_table.py"""
import json
from pathlib import Path

R = Path(__file__).resolve().parent
d = json.loads((R / 'FULL_EAS_TURBO.json').read_text(encoding='utf-8'))
usd = lambda v: '-' if v is None else f'${v:,.0f}'  # noqa: E731
pct = lambda v: '-' if v is None else f'{100 * v:.0f}%'  # noqa: E731
day = lambda v: '-' if v is None else f'{v:g}'  # noqa: E731
md = ['# Full EA portfolio on the Turbo $50k reward-account rules (generated by full_eas_table.py)', '',
      'Python/numba replay of the frozen Full EA native ledgers (website full-eas stream, 2021-10 → 2026-10), same firm model as sim.py.',
      '**MC** = 1,000 three-year paths of resampled 4-week blocks. **History** = every weekday start 2021-10 → 2025-10, 12 months each (the recorded sequence).',
      'Breach = pessimistic (every open position at its full stop). Income = 80% trader share; per month = total paid ÷ 36 (MC) or ÷ 12 (history),',
      'so accounts that ended early earn nothing afterwards. In-sample; backtest income is not a forecast.', '',
      '| Portfolio | Risk | Income / month, 3y MC mean / median | Income / month, history 1y mean | Breach 3y MC | Breach ≤ 1y history | Avg days to breach MC (median) | Avg days to breach history (median) | Frozen 3y | Worst day MC / history | Max closed DD MC median / worst / history worst | Trades / month | / day |',
      '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
for v in d.values():
    m, h = v['mc3'], v['hist1']
    md.append(f"| {v['code']} {v['portfolio']} ({v['members']}) | {v['risk']:g}% | {usd(m['income_total_mean'] / 36)} / {usd(m['income_total_median'] / 36)} | {usd(h['income_total_mean'] / 12)} | "
              f"{pct(m['breach'])} | {pct(h['breach_365'])} | {day(m['breach_days_mean'])} ({day(m['breach_days_median'])}) | {day(h['breach_days_mean'])} ({day(h['breach_days_median'])}) | "
              f"{pct(m['freeze'])} | {usd(m['worst_day'])} / {usd(h['worst_day'])} | {usd(m['dd_closed_median'])} / {usd(m['dd_closed_worst'])} / {usd(h['dd_closed_worst'])} | "
              f"{h['trades_per_month']} | {h['trades_per_day']} |")
(R / 'FULL_EAS_TURBO.md').write_text('\n'.join(md) + '\n', encoding='utf-8'); print('\n'.join(md[7:]))
